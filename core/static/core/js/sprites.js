  function drawFrame(ctx, sprite, frame, dx, dy, scale, palOverride) {
    const s = scale || 1;
    const pal = palOverride ? Object.assign({}, sprite.palette, palOverride) : sprite.palette;
    const rows = sprite.frames[frame % sprite.frames.length];
    for (let y = 0; y < sprite.h; y++) {
      const row = rows[y];
      for (let x = 0; x < sprite.w; x++) {
        const c = pal[row[x]];
        if (!c) continue;
        ctx.fillStyle = c;
        ctx.fillRect(dx + x * s, dy + y * s, s, s);
      }
    }
  }

  /** All frames laid out horizontally on one canvas (1px = 1px). */
  function toSheet(sprite, palOverride) {
    const c = document.createElement("canvas");
    c.width = sprite.w * sprite.frames.length;
    c.height = sprite.h;
    const ctx = c.getContext("2d");
    sprite.frames.forEach(function (_, i) { drawFrame(ctx, sprite, i, i * sprite.w, 0, 1, palOverride); });
    return c;
  }

